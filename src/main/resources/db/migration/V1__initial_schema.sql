-- ArtConnect initial schema (PostgreSQL)

CREATE TABLE app_users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(30)  NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    role          VARCHAR(20)  NOT NULL,
    display_name  VARCHAR(60)  NOT NULL,
    bio           VARCHAR(1000),
    avatar_url    VARCHAR(500),
    location      VARCHAR(100),
    website       VARCHAR(200),
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT chk_users_role CHECK (role IN ('ARTIST', 'COLLECTOR', 'ADMIN'))
);

CREATE TABLE auth_tokens (
    token_hash VARCHAR(64) PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES app_users (id) ON DELETE CASCADE,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_auth_tokens_expires_at ON auth_tokens (expires_at);

CREATE TABLE artworks (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    artist_id         BIGINT        NOT NULL REFERENCES app_users (id) ON DELETE CASCADE,
    title             VARCHAR(120)  NOT NULL,
    description       VARCHAR(2000) NOT NULL,
    price             NUMERIC(12, 2) NOT NULL,
    category          VARCHAR(40)   NOT NULL,
    medium            VARCHAR(100),
    dimensions        VARCHAR(100),
    creation_year     INTEGER,
    image_url         VARCHAR(500)  NOT NULL,
    sale_type         VARCHAR(10)   NOT NULL,
    status            VARCHAR(10)   NOT NULL,
    auction_ends_at   TIMESTAMP WITH TIME ZONE,
    current_bid       NUMERIC(12, 2),
    highest_bidder_id BIGINT REFERENCES app_users (id) ON DELETE SET NULL,
    bid_count         INTEGER          NOT NULL DEFAULT 0,
    average_rating    DOUBLE PRECISION NOT NULL DEFAULT 0,
    review_count      INTEGER          NOT NULL DEFAULT 0,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT chk_artworks_price CHECK (price > 0),
    CONSTRAINT chk_artworks_sale_type CHECK (sale_type IN ('FIXED', 'AUCTION')),
    CONSTRAINT chk_artworks_status CHECK (status IN ('AVAILABLE', 'SOLD'))
);
CREATE INDEX idx_artworks_artist ON artworks (artist_id);
CREATE INDEX idx_artworks_category ON artworks (category);
CREATE INDEX idx_artworks_sale_status ON artworks (sale_type, status, auction_ends_at);

CREATE TABLE artwork_tags (
    artwork_id BIGINT      NOT NULL REFERENCES artworks (id) ON DELETE CASCADE,
    tag        VARCHAR(40) NOT NULL
);
CREATE INDEX idx_artwork_tags_artwork ON artwork_tags (artwork_id);
CREATE INDEX idx_artwork_tags_tag ON artwork_tags (tag);

CREATE TABLE bids (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    artwork_id BIGINT         NOT NULL REFERENCES artworks (id) ON DELETE CASCADE,
    bidder_id  BIGINT         NOT NULL REFERENCES app_users (id) ON DELETE CASCADE,
    amount     NUMERIC(12, 2) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_bids_artwork ON bids (artwork_id);
CREATE INDEX idx_bids_bidder ON bids (bidder_id);

CREATE TABLE reviews (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    artwork_id BIGINT        NOT NULL REFERENCES artworks (id) ON DELETE CASCADE,
    author_id  BIGINT        NOT NULL REFERENCES app_users (id) ON DELETE CASCADE,
    rating     INTEGER       NOT NULL,
    comment    VARCHAR(1000) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_reviews_artwork_author UNIQUE (artwork_id, author_id),
    CONSTRAINT chk_reviews_rating CHECK (rating BETWEEN 1 AND 5)
);

CREATE TABLE orders (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    artwork_id    BIGINT REFERENCES artworks (id) ON DELETE SET NULL,
    buyer_id      BIGINT         NOT NULL REFERENCES app_users (id) ON DELETE CASCADE,
    artist_id     BIGINT         NOT NULL REFERENCES app_users (id) ON DELETE CASCADE,
    artwork_title VARCHAR(120)   NOT NULL,
    image_url     VARCHAR(500)   NOT NULL,
    price         NUMERIC(12, 2) NOT NULL,
    source        VARCHAR(10)    NOT NULL,
    status        VARCHAR(10)    NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT chk_orders_source CHECK (source IN ('PURCHASE', 'AUCTION')),
    CONSTRAINT chk_orders_status CHECK (status IN ('PENDING', 'COMPLETED', 'CANCELLED'))
);
CREATE INDEX idx_orders_buyer ON orders (buyer_id);
CREATE INDEX idx_orders_artist ON orders (artist_id);

CREATE TABLE exhibitions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    curator_id  BIGINT        NOT NULL REFERENCES app_users (id) ON DELETE CASCADE,
    title       VARCHAR(120)  NOT NULL,
    description VARCHAR(2000) NOT NULL,
    start_date  DATE          NOT NULL,
    end_date    DATE          NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT chk_exhibitions_dates CHECK (end_date >= start_date)
);
CREATE INDEX idx_exhibitions_curator ON exhibitions (curator_id);

CREATE TABLE exhibition_artworks (
    exhibition_id BIGINT  NOT NULL REFERENCES exhibitions (id) ON DELETE CASCADE,
    artwork_id    BIGINT  NOT NULL REFERENCES artworks (id) ON DELETE CASCADE,
    position      INTEGER NOT NULL,
    PRIMARY KEY (exhibition_id, position)
);
CREATE INDEX idx_exhibition_artworks_artwork ON exhibition_artworks (artwork_id);
