-- Billing contact collected at checkout, invoice numbers, and a log of invoice notifications.

ALTER TABLE orders ADD COLUMN billing_email VARCHAR(254);
ALTER TABLE orders ADD COLUMN billing_phone VARCHAR(20);
-- UPI, CARD, NETBANKING, WALLET (or ONLINE when the gateway doesn't say)
ALTER TABLE orders ADD COLUMN payment_method VARCHAR(20);
ALTER TABLE orders ADD COLUMN invoice_number VARCHAR(30);
CREATE UNIQUE INDEX ux_orders_invoice_number ON orders (invoice_number);

-- Invoices already paid before this migration get a number too
UPDATE orders
SET invoice_number = 'INV-' || CAST(CAST(EXTRACT(YEAR FROM paid_at) AS INTEGER) AS VARCHAR(4))
                     || '-' || LPAD(CAST(id AS VARCHAR(12)), 6, '0')
WHERE paid_at IS NOT NULL;

CREATE TABLE notifications (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   BIGINT       NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    channel    VARCHAR(10)  NOT NULL,
    recipient  VARCHAR(254) NOT NULL,
    subject    VARCHAR(200),
    status     VARCHAR(10)  NOT NULL,
    provider   VARCHAR(20)  NOT NULL,
    error      VARCHAR(500),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT chk_notifications_channel CHECK (channel IN ('EMAIL', 'SMS')),
    CONSTRAINT chk_notifications_status CHECK (status IN ('SENT', 'SIMULATED', 'FAILED'))
);
CREATE INDEX idx_notifications_order ON notifications (order_id);
