-- Shopping cart, and checkouts: one payment, shipping address and invoice covering one or more orders.

CREATE TABLE cart_items (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES app_users (id) ON DELETE CASCADE,
    artwork_id BIGINT NOT NULL REFERENCES artworks (id) ON DELETE CASCADE,
    added_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_cart_items_user_artwork UNIQUE (user_id, artwork_id)
);
CREATE INDEX idx_cart_items_user ON cart_items (user_id);

CREATE TABLE checkouts (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    buyer_id          BIGINT         NOT NULL REFERENCES app_users (id) ON DELETE CASCADE,
    status            VARCHAR(20)    NOT NULL,
    total             NUMERIC(12, 2) NOT NULL,
    billing_email     VARCHAR(254),
    ship_name         VARCHAR(100),
    ship_line1        VARCHAR(200),
    ship_line2        VARCHAR(200),
    ship_city         VARCHAR(100),
    ship_state        VARCHAR(100),
    ship_postal_code  VARCHAR(10),
    ship_country      VARCHAR(60),
    payment_provider  VARCHAR(20),
    provider_order_id VARCHAR(64),
    payment_id        VARCHAR(64),
    payment_method    VARCHAR(20),
    paid_at           TIMESTAMP WITH TIME ZONE,
    hold_expires_at   TIMESTAMP WITH TIME ZONE,
    invoice_number    VARCHAR(30),
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    -- Only used while carrying existing orders over below
    legacy_order_id   BIGINT,
    CONSTRAINT chk_checkouts_status CHECK (status IN ('AWAITING_PAYMENT', 'PAID', 'CANCELLED'))
);
CREATE UNIQUE INDEX ux_checkouts_provider_order ON checkouts (provider_order_id);
CREATE UNIQUE INDEX ux_checkouts_invoice_number ON checkouts (invoice_number);
CREATE INDEX idx_checkouts_buyer ON checkouts (buyer_id);
CREATE INDEX idx_checkouts_status_hold ON checkouts (status, hold_expires_at);

ALTER TABLE orders ADD COLUMN checkout_id BIGINT REFERENCES checkouts (id) ON DELETE SET NULL;
CREATE INDEX idx_orders_checkout ON orders (checkout_id);
-- Every order in a checkout shares the checkout's invoice number
DROP INDEX ux_orders_invoice_number;

-- Carry over orders that already started (or finished) online payment: each becomes its own checkout
INSERT INTO checkouts (buyer_id, status, total, billing_email, payment_provider, provider_order_id, payment_id,
                       payment_method, paid_at, hold_expires_at, invoice_number, created_at, updated_at, legacy_order_id)
SELECT buyer_id,
       CASE WHEN status IN ('PAID', 'COMPLETED') THEN 'PAID' ELSE status END,
       price, billing_email, payment_provider, provider_order_id, payment_id, payment_method, paid_at,
       hold_expires_at, invoice_number, created_at, updated_at, id
FROM orders
WHERE provider_order_id IS NOT NULL OR invoice_number IS NOT NULL;

UPDATE orders SET checkout_id = (SELECT c.id FROM checkouts c WHERE c.legacy_order_id = orders.id)
WHERE EXISTS (SELECT 1 FROM checkouts c WHERE c.legacy_order_id = orders.id);

-- Payment details now live on the checkout
DROP INDEX ux_orders_provider_order;
UPDATE orders SET provider_order_id = NULL;

ALTER TABLE checkouts DROP COLUMN legacy_order_id;

-- Invoice emails belong to the checkout
ALTER TABLE notifications ADD COLUMN checkout_id BIGINT REFERENCES checkouts (id) ON DELETE CASCADE;
UPDATE notifications SET checkout_id = (SELECT o.checkout_id FROM orders o WHERE o.id = notifications.order_id);
ALTER TABLE notifications ALTER COLUMN order_id DROP NOT NULL;
CREATE INDEX idx_notifications_checkout ON notifications (checkout_id);
